import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const tokens=fs.readFileSync(path.join(root,'app/styles/tokens.css'),'utf8');
const product=fs.readFileSync(path.join(root,'app/styles/components.css'),'utf8');
const fail=(m)=>{throw new Error(m)};
if(!tokens.includes('--floating-nav-bottom-browser')) fail('browser bottom token missing');
if(!product.includes('.floating-navigation')) fail('floating navigation styles missing');
if(!product.includes('env(safe-area-inset-bottom')) fail('safe-area placement missing');
console.log('floating navigation placement passed');
