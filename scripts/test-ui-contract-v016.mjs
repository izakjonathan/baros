import fs from 'node:fs';
import { readStyles } from './read-styles.mjs';
const layout=fs.readFileSync('app/layout.tsx','utf8');
const css=readStyles();
const app=fs.readFileSync('components/bar-ops-app.tsx','utf8');
const shell=fs.readFileSync('components/app-shell.tsx','utf8');
const assert=(condition,message)=>{if(!condition) throw new Error(message)};
assert((layout.match(/import ".*\.css";/g)||[]).length===1,'Root layout must load one CSS entrypoint');
assert(layout.includes('import "./globals.css";'),'Root layout must load globals.css');
assert(css.includes('.floating-navigation'),'Floating navigation contract missing');
assert(css.includes('.modal-content'),'Modal scrolling contract missing');
assert(app.includes('FloatingNavigation') || shell.includes('FloatingNavigation'),'Floating navigation component missing');
console.log('v0.17.0 UI contract passed');
