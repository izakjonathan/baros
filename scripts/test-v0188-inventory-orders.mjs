import fs from "node:fs";
const pkg=JSON.parse(fs.readFileSync("package.json","utf8"));
const app=fs.readFileSync("components/bar-ops-app.tsx","utf8");
const inventory=fs.readFileSync("features/inventory/InventoryWorkspace.module.css","utf8");
const orders=fs.readFileSync("features/orders/OrdersWorkspace.module.css","utf8");
const fail=(m)=>{console.error(`v0.18.8 regression: ${m}`);process.exit(1)};
if(pkg.version!=="0.18.8")fail("package version mismatch");
if(!app.includes('inventoryStyles from "@/features/inventory/InventoryWorkspace.module.css"'))fail("inventory module import missing");
if(!app.includes('orderStyles from "@/features/orders/OrdersWorkspace.module.css"'))fail("orders module import missing");
if(!app.includes('className={`${inventoryStyles.workspace} page-flow`}'))fail("inventory workspace owner missing");
if(!app.includes('className={`${orderStyles.workspace} page-flow`}'))fail("orders workspace owner missing");
if(!inventory.includes('@media(max-width:640px)'))fail("inventory mobile rules missing");
if(!orders.includes('@media(max-width:640px)'))fail("orders mobile rules missing");
if(!inventory.includes('grid-template-columns:1fr'))fail("inventory mobile cards missing");
if(!orders.includes('grid-template-columns:1fr'))fail("orders mobile cards missing");
console.log("v0.18.8 inventory and orders redesign regression passed");
