import fs from "node:fs";
const pkg=JSON.parse(fs.readFileSync("package.json","utf8"));
const workflow=fs.readFileSync(".github/workflows/quality.yml","utf8");
const preflight=fs.readFileSync("scripts/preflight-stabilization.mjs","utf8");
const artifact=fs.readFileSync("scripts/check-release-artifacts.mjs","utf8");
const fail=(m)=>{console.error(`v0.18.4.14.1 regression: ${m}`);process.exit(1)};
if(pkg.version!=="0.18.4.14.1") fail("package version mismatch");
if(pkg.scripts?.["audit:artifacts"]!=="node scripts/check-release-artifacts.mjs") fail("artifact audit script missing");
const artifactStep=workflow.indexOf("Check release artifacts before dependency installation");
const installStep=workflow.indexOf("Install dependencies");
if(artifactStep<0||installStep<0||artifactStep>installStep) fail("artifact audit must run before npm install");
if(preflight.includes('["node_modules", ".next"')) fail("stabilization preflight still rejects install-created node_modules");
for(const required of ["node_modules","vercel.json","public/offline.html"]) if(!artifact.includes(`"${required}"`)) fail(`artifact checker does not cover ${required}`);
console.log("v0.18.4.14.1 quality-check ordering regression passed");
