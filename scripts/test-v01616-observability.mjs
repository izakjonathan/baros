import fs from "node:fs";
const release=fs.readFileSync("lib/release.ts","utf8");
const obs=fs.readFileSync("lib/observability.ts","utf8");
const live=fs.readFileSync("app/api/health/live/route.ts","utf8");
const ready=fs.readFileSync("app/api/health/ready/route.ts","utf8");
const proxy=fs.readFileSync("proxy.ts","utf8");
for(const token of ["VERCEL_GIT_COMMIT_SHA","publicReleaseInfo","releaseHeaders"]) if(!release.includes(token)) throw new Error(`missing release metadata: ${token}`);
for(const token of ["logServerEvent","version: releaseInfo.version","commit: releaseInfo.commit"]) if(!obs.includes(token)) throw new Error(`missing structured observability: ${token}`);
if(!ready.includes("durationMs")||!ready.includes('"health.readiness"')) throw new Error("readiness timing/logging missing");
if(!live.includes("publicReleaseInfo")||!ready.includes("publicReleaseInfo")) throw new Error("health release diagnostics missing");
if(!proxy.includes("releaseHeaders()")) throw new Error("API release headers missing");
console.log("v0.16.16 operational observability checks passed");
